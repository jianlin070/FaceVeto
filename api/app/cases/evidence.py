"""Evidence pack: case facts as JSON plus a Gemini-drafted Markdown report (template fallback)."""
import logging
from datetime import timedelta, timezone

from app.agent.gemini import draft_evidence_report
from app.db import SERVER_TS, age_days, get_db

log = logging.getLogger(__name__)
LOCAL_TZ = timezone(timedelta(hours=8), "UTC+8 (Kuala Lumpur / Singapore)")


def _t(ts):
    if not ts:
        return None
    return {"utc": ts.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
            "local": ts.astimezone(LOCAL_TZ).strftime("%Y-%m-%d %H:%M:%S UTC+8")}


def case_facts(case_id: str) -> dict:
    db = get_db()
    case = db.collection("cases").document(case_id).get().to_dict()
    post = db.collection("posts").document(case["post_id"]).get().to_dict() or {}
    poster = db.collection("users").document(case["poster_uid"]).get().to_dict() or {}
    a = post.get("assessment") or {}
    timeline = [{"event": "Post uploaded and held by FaceVeto", "time": _t(post.get("created_at"))}]
    if case.get("owner_response"):
        r = case["owner_response"]
        label = "Owner reported: Not me (post removed)" if r["value"] == "not_me" else "Owner confirmed: It's me (post allowed)"
        timeline.append({"event": label, "time": _t(r.get("at"))})
    if case.get("admin_action"):
        r = case["admin_action"]
        timeline.append({"event": f"Review team action: {r['value']}", "time": _t(r.get("at")), "note": r.get("note", "")})
    return {
        "case_id": case_id, "post_id": case["post_id"], "status": case["status"],
        "poster_handle": post.get("author_handle", ""), "poster_account_age_days": age_days(poster.get("created_at")),
        "caption": post.get("caption", ""), "category": case.get("category"), "severity": case.get("severity"),
        "confidence": case.get("confidence"), "face_match_similarity": case.get("similarity"),
        "text_in_image": a.get("text_in_image", ""), "evidence": a.get("evidence", []),
        "ai_reasoning": a.get("reasoning", ""), "languages": a.get("languages", []),
        "decision": post.get("decision"), "timeline": timeline, "local_timezone": LOCAL_TZ.tzname(None),
    }


def template_report(f: dict) -> str:
    rows = "\n".join(f"| {e['time']['utc'] if e['time'] else ''} | {e['time']['local'] if e['time'] else ''} | {e['event']} |" for e in f["timeline"])
    ev = "\n".join(f"- {e}" for e in f["evidence"]) or "- (none recorded)"
    return f"""## Summary
A post by @{f['poster_handle']} used the face of a protected user without consent. FaceVeto held it as {f['category']} (severity {f['severity']}).

## Timeline
| UTC | Local | Event |
|---|---|---|
{rows}

## What the content shows
Caption: "{f['caption'][:300]}". Text in image: "{f['text_in_image'][:300]}".

## Why it is harmful
Category: {f['category']}. Evidence:
{ev}

## Actions taken
Post status: {f['status']}. The image is preserved in quarantine for 30 days.

## Suggested next steps
- Keep this evidence pack.
- Report the account to the platform. If money, threats or intimate images are involved, report to the police.
- Do not engage with the poster.

_Generated by FaceVeto (AI-assisted). Verify before filing._"""


def generate_evidence(case_id: str) -> str:
    facts = case_facts(case_id)
    report = draft_evidence_report(facts) or template_report(facts)
    get_db().collection("cases").document(case_id).update({"evidence_report_md": report, "evidence_at": SERVER_TS})
    log.info("evidence pack generated", extra={"fields": {"case_id": case_id}})
    return report
